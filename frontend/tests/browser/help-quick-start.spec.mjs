test('Workspace image failure retains the instructions and leaves tool guides usable', async ({ page }) => {
  await page.route('**/help-guides/12-workspace.webp', route => route.abort())
  await page.goto('/enzymind/help')
  const guide = quickStart(page).locator('.workspace-guide-browser')
  await guide.scrollIntoViewIfNeeded()
  await expect(guide.getByText(/Image unavailable/)).toBeVisible()
  await expect(guide.getByRole('button', { name: 'View full guide', exact: true })).toBeDisabled()
  await expect(guide.locator('.guide-steps')).toContainText('Add to question')
  await expect(guide.getByRole('link', { name: 'Open Workspace', exact: true })).toHaveAttribute('href', '/enzymind/agent')
  await expectGuideImage(page, 'recognize')
})

async function expectGuideImage(page, id) {
  await image(page).scrollIntoViewIfNeeded()
  await expect(image(page)).toHaveAttribute('data-guide-id', id)
  await expect(toolGuide(page).locator('.guide-preview')).toHaveClass(/loaded/)
  expect(await image(page).evaluate(el => el.complete && el.naturalWidth === 2200)).toBe(true)
}

test('all eleven tools have distinct guides and correct destinations, loaded on selection', async ({ page }) => {
  const requests = new Set()
  const errors = []
  page.on('request', request => { if (request.resourceType() === 'image' && request.url().includes('/help-guides/') && !request.url().includes('12-workspace')) requests.add(request.url()) })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/enzymind/help')
  await expectGuideImage(page, 'recognize')
  expect(requests.size).toBe(1)
  await expect(quickStart(page).locator('.guide-tool-picker button')).toHaveCount(7)
  await expect(quickStart(page).locator('.help-more details[open]')).toHaveCount(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)

  const sources = new Set()
  for (const group of ['Prediction', 'Utility']) {
    await category(page, group).click()
    await expect(quickStart(page).locator('.guide-tool-picker button')).toHaveCount(group === 'Prediction' ? 7 : 4)
    for (const tool of TOOLS.filter(tool => tool.path.startsWith(group === 'Prediction' ? '/predict/' : '/utility/'))) {
      await quickStart(page).getByRole('button', { name: tool.title, exact: true }).click()
      await expectGuideImage(page, tool.id)
      await expect(quickStart(page).getByRole('link', { name: `Open ${tool.title}`, exact: true })).toHaveAttribute('href', `/enzymind${tool.path}`)
      await expect(toolGuide(page).locator('.guide-steps')).toContainText(tool.action)
      sources.add(await image(page).getAttribute('src'))
    }
  }
  expect(sources.size).toBe(11)
  expect(requests.size).toBe(11)
  expect(errors).toEqual([])

  await category(page, 'Prediction').click()
  await quickStart(page).getByRole('button', { name: 'Kcat Prediction', exact: true }).click()
  await category(page, 'Utility').click()
  await category(page, 'Prediction').click()
  await expectGuideImage(page, 'kcat')
  await page.locator('.section-nav a[href="#api-base-url"]').click()
  await expect(page).toHaveURL(/#api-base-url$/)
  await expect(page.locator('#api-base-url h2')).toBeInViewport()
})

test('full guide supports zoom, modal keyboard focus and returning to the reading position', async ({ page }) => {
  await page.goto('/enzymind/help')
  await expectGuideImage(page, 'recognize')
  const opener = toolGuide(page).getByRole('button', { name: 'View full guide', exact: true })
  await opener.scrollIntoViewIfNeeded()
  const before = await page.evaluate(() => window.scrollY)
  await opener.click()
  const dialog = page.getByRole('dialog', { name: 'Enzyme Recognition' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Close full guide' })).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden')
  // Measure the fitted image after the opening layout and animation settle.
  await dialog.evaluate(async el => {
    await Promise.all(el.getAnimations().map(animation => animation.finished))
    await new Promise(requestAnimationFrame)
  })
  const fittedWidth = await dialog.locator('img').evaluate(el => el.clientWidth)
  await dialog.getByRole('button', { name: 'Zoom in', exact: true }).click()
  expect(await dialog.locator('img').evaluate(el => el.clientWidth)).toBeGreaterThan(fittedWidth)
  await dialog.getByRole('button', { name: '100%', exact: true }).click()
  await expect(dialog.locator('output')).toHaveText('100%')
  expect(await dialog.locator('.image-dialog-viewport').evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  await dialog.getByRole('button', { name: 'Fit', exact: true }).click()
  expect(await dialog.locator('img').evaluate(el => el.clientWidth)).toBeCloseTo(fittedWidth, 0)
  await dialog.getByRole('button', { name: 'Close full guide' }).focus()
  for (let i = 0; i < 9; i++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBe(true)
  }
  await page.screenshot({ path: '/tmp/enzymind-quick-start-dialog.png' })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
  expect(Math.abs(await page.evaluate(() => window.scrollY) - before)).toBeLessThan(3)
})

test('mobile guide selection, disclosure controls and zoom stay within the page', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/enzymind/help')
  await category(page, 'Utility').click()
  await quickStart(page).getByRole('button', { name: 'Structure Prediction', exact: true }).click()
  await expectGuideImage(page, 'structure')
  // Other Help sections already overflow on mobile; constrain this change to Quick Start.
  expect(await quickStart(page).evaluate(el => el.getBoundingClientRect().right <= innerWidth && el.scrollWidth <= el.clientWidth)).toBe(true)
  const pageWidth = await page.evaluate(() => document.documentElement.scrollWidth)
  await quickStart(page).getByRole('button', { name: 'View full Structure Prediction guide', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '100%', exact: true }).click()
  expect(await dialog.locator('.image-dialog-viewport').evaluate(el => el.scrollWidth > el.clientWidth && el.scrollHeight > el.clientHeight)).toBe(true)
  expect(await dialog.evaluate(el => el.getBoundingClientRect().right <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(pageWidth)
  await dialog.getByRole('button', { name: 'Close full guide' }).click()

  const inputs = quickStart(page).locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Inputs & molecules' }) })
  await inputs.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(inputs).toHaveAttribute('open', '')
  await expect(inputs).toContainText('Invalid amino acids are reported')
  await inputs.locator('summary').click()
  await quickStart(page).getByRole('button', { name: 'Details', exact: true }).click()
  const downloads = quickStart(page).locator('details').filter({ has: page.locator('summary').filter({ hasText: 'Downloads & recovery' }) })
  await expect(downloads).toHaveAttribute('open', '')
  await expect(downloads.locator('summary')).toBeFocused()
  await expect(downloads).toContainText('90 days after creation')
  await page.screenshot({ path: '/tmp/enzymind-quick-start-mobile.png', fullPage: true })
})

test('reduced motion disables guide transitions and image load failures keep instructions usable', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/enzymind/help')
  await expectGuideImage(page, 'recognize')
  expect(await image(page).evaluate(el => parseFloat(getComputedStyle(el).transitionDuration))).toBeLessThanOrEqual(0.001)
  await toolGuide(page).getByRole('button', { name: 'View full guide', exact: true }).click()
  expect(await page.getByRole('dialog').evaluate(el => getComputedStyle(el).animationName)).toBe('none')
  await page.keyboard.press('Escape')
  await page.route('**/help-guides/*km-prediction.webp', route => route.abort())
  await quickStart(page).getByRole('button', { name: 'Km Prediction', exact: true }).click()
  await expect(quickStart(page).getByText(/Image unavailable/)).toBeVisible()
  await expect(quickStart(page).getByRole('link', { name: 'Open Km Prediction', exact: true })).toHaveAttribute('href', '/enzymind/predict/km')
  await expect(toolGuide(page).locator('.guide-steps')).toContainText('mM')
})
